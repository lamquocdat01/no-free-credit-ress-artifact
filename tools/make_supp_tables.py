"""Write manuscript/supp_tables.tex: every supplementary table, generated from results/*.json (no hand-typed numbers)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "data" / "results"


def J(n):
    return json.load(open(R / n, encoding="utf-8"))


def P(x, d=1):
    return "--" if x is None else f"{100 * x:.{d}f}\\%"


def F(x, d=2):
    return "--" if x is None else f"{x:.{d}f}"


def tab(label, caption, cols, head, rows, small=True):
    L = [r"\begin{table}[H]", r"\centering", r"\caption{" + caption + "}", r"\label{" + label + "}"]
    if small:
        L.append(r"\small")
    L += [r"\begin{tabular}{@{}" + cols + "@{}}", r"\toprule", " & ".join(head) + r" \\", r"\midrule"]
    L += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L)


def longtab(label, caption, cols, head, rows):
    L = [r"\begin{longtable}{@{}" + cols + "@{}}", r"\caption{" + caption + r"}\label{" + label + r"}\\", r"\toprule",
         " & ".join(head) + r" \\", r"\midrule", r"\endfirsthead", r"\toprule", " & ".join(head) + r" \\", r"\midrule",
         r"\endhead", r"\bottomrule", r"\endlastfoot"]
    L += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
    L += [r"\end{longtable}", ""]
    return "\n".join(L)


